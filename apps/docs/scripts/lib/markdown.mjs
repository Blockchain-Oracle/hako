/**
 * Markdown helpers for generated MDX. Catalog text is written for agents and may contain `{`, `<`, `*`, `|` or `~`,
 * which MDX or GFM would read as syntax. Text outside code spans is escaped; code spans are kept as written.
 */

const CODE_SPAN = /`[^`\n]*`/g;
const PLAIN_SPECIALS = /[\\`{}<>*_[\]|~#]/g;
const MIN_FENCE_TICKS = 3; // CommonMark: a code fence is at least three backticks

function escapePlain(text) {
  return text.replace(PLAIN_SPECIALS, (char) => `\\${char}`);
}

function mapOutsideCode(value, plain, span) {
  const parts = [];
  let last = 0;
  for (const match of value.matchAll(CODE_SPAN)) {
    parts.push(plain(value.slice(last, match.index)), span(match[0]));
    last = match.index + match[0].length;
  }
  parts.push(plain(value.slice(last)));
  return parts.join("");
}

/** Prose from the catalog, safe for an MDX paragraph. */
export function mdText(value) {
  return mapOutsideCode(String(value ?? ""), escapePlain, (span) => span);
}

/** Prose for a GFM table cell: one line, pipes escaped (inside code spans too, as GFM requires). */
export function mdCell(value) {
  const oneLine = String(value ?? "").replace(/\s*\n\s*/g, " ");
  return mapOutsideCode(oneLine, escapePlain, (span) => span.replaceAll("|", "\\|"));
}

/** An inline code span for a literal value (field names, patterns, JSON). */
export function code(value) {
  const text = String(value);
  return text.includes("`") ? `\`\` ${text} \`\`` : `\`${text}\``;
}

/** A code span for a table cell. */
export function codeCell(value) {
  return code(value).replaceAll("|", "\\|");
}

export function table(headers, rows) {
  const line = (cells) => `| ${cells.join(" | ")} |`;
  return [line(headers), line(headers.map(() => "---")), ...rows.map(line)].join("\n");
}

/** A fenced block; the fence is longer than any backtick run in the body. */
export function fence(lang, body, title) {
  const longest = Math.max(0, ...[...body.matchAll(/`+/g)].map((m) => m[0].length));
  const ticks = "`".repeat(Math.max(MIN_FENCE_TICKS, longest + 1));
  const meta = title ? ` title=${JSON.stringify(title)}` : "";
  return `${ticks}${lang}${meta}\n${body}\n${ticks}`;
}

export function frontmatter(fields) {
  const lines = Object.entries(fields).map(([key, value]) => `${key}: ${JSON.stringify(value)}`);
  return `---\n${lines.join("\n")}\n---`;
}

