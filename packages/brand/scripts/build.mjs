// Generates the brand from its two sources (Kawase's Senryo pipeline, tamion/packages/ui-tokens/build.mjs):
//   tokens.json → generated/web.css (shadcn variable names + Tailwind 4 `@theme inline` + type utilities)
//               → generated/tokens.ts (the same values for code that cannot use class names)
//   mark.json   → generated/mark.ts and assets/{hako-mark,hako-mark-adaptive,hako-mark-ink,hako-mark-inverse,app-icon,favicon}.svg
// Run: pnpm --filter @hako/brand build (this script, then check-contrast.mjs, which fails the build below 4.5:1).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const here = (file) => new URL(`../${file}`, import.meta.url);
const tokens = JSON.parse(readFileSync(here("tokens.json"), "utf8"));
const mark = JSON.parse(readFileSync(here("mark.json"), "utf8"));
const HEADER = "/* GENERATED from tokens.json by scripts/build.mjs. Do not edit; change tokens.json and rebuild. */\n";
const TS_HEADER = "// GENERATED by scripts/build.mjs from tokens.json and mark.json. Do not edit; change the source and rebuild.\n";
const RADIUS_STEP = 4;
const PILL = 999;
const INK = "#000000";
const PAPER = "#FFFFFF";

// ---- tokens → web.css -------------------------------------------------------------------------------------------

const themes = { light: tokens.themes.light, dark: tokens.themes.dark };
const names = Object.keys(themes.light);
for (const [theme, values] of Object.entries(themes)) {
  const missing = names.filter((name) => !(name in values));
  const extra = Object.keys(values).filter((name) => !names.includes(name));
  if (missing.length || extra.length) throw new Error(`theme ${theme}: missing ${missing.join(", ")} extra ${extra.join(", ")}`);
}
if (themes.light.accent !== tokens.accent.value) throw new Error("themes.light.accent must equal accent.value");

const radius = tokens.radius;
const radii = { sm: radius - RADIUS_STEP, md: radius - RADIUS_STEP / 2, lg: radius, xl: radius + RADIUS_STEP };
// Senryo's own corner steps (8/12/16/24/32) ride along as --radius-step-* (`rounded-step-lg`) for code that wants the
// exact values (Kawase's `--radius-s-*` would read as Tailwind's start-corner utilities, `rounded-s-*`).
const senryoRadii = Object.entries(tokens.scale.radius).filter(([, v]) => v < PILL).map(([k, v]) => [`step-${k}`, v]);
const vars = (values, indent) => Object.entries(values).map(([k, v]) => `${indent}--${k}: ${v};`).join("\n");
const quote = (family) => (/\s/.test(family) ? `"${family}"` : family);
const fallback = tokens.fonts.fallback.map(quote).join(", ");
const stack = (font) => `var(${font.variable}), ${quote(font.family)}, ${fallback}`;
const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const px = (value) => `${value}px`;
const shadow = ({ x, y, blur, spread, color }) => `${px(x)} ${px(y)} ${px(blur)} ${px(spread)} ${color}`;
const bezier = (points) => `cubic-bezier(${points.join(", ")})`;
const { motion, layout } = tokens.scale;

// Utilities carry the stacks themselves: `@theme inline` values are not emitted as CSS variables.
const families = { sans: stack(tokens.fonts.body), display: stack(tokens.fonts.display) };

// One utility per Senryo type role (`type-page-title`, `type-row-amount`…): money roles get tabular lining figures.
const typeUtilities = Object.entries(tokens.scale.type)
  .map(([role, t]) => {
    const lines = [
      `  font-family: ${families[t.font]};`,
      `  font-size: ${px(t.size)};`,
      `  line-height: ${px(t.lineHeight)};`,
      `  font-weight: ${t.weight};`,
      `  letter-spacing: ${t.tracking ? `${t.tracking}em` : "0"};`,
    ];
    if (t.numeric) lines.push("  font-variant-numeric: tabular-nums lining-nums;");
    return `@utility type-${kebab(role)} {\n${lines.join("\n")}\n}`;
  })
  .join("\n\n");

const web = `${HEADER}/*
 * ${tokens.name}: light is the default, dark is an adaptation (\`.dark\` on <html>). Accent: ${tokens.accent.name} (${tokens.accent.kanji}) ${tokens.accent.value},
 * a fill with a black label for selected controls, the focus ring and badges; text in its family is \`link\`.
 */
:root {
  color-scheme: light;
${vars(themes.light, "  ")}
  --radius: ${px(radius)};
}

.dark {
  color-scheme: dark;
${vars(themes.dark, "  ")}
}

@theme inline {
${names.map((name) => `  --color-${name}: var(--${name});`).join("\n")}
${[...Object.entries(radii), ...senryoRadii].map(([k, v]) => `  --radius-${k}: ${px(v)};`).join("\n")}
  --font-sans: ${families.sans};
  --font-display: ${families.display};
  --font-mono: ${tokens.fonts.mono.map(quote).join(", ")};
${Object.entries(tokens.scale.elevation).map(([k, v]) => `  --shadow-${kebab(k)}: ${shadow(v)};`).join("\n")}
  --ease-senryo: ${bezier(motion.easing)};
  --ease-sheet: ${bezier(motion.sheetEasing)};
  --ease-overshoot: ${bezier(motion.overshootEasing)};
  --container-measure: ${px(layout.measure)};
}

/* Money: Roboto Condensed Black with tabular lining figures (amounts, balances, prices). */
@utility money {
  font-family: ${families.display};
  font-weight: 900;
  font-variant-numeric: tabular-nums lining-nums;
  letter-spacing: -0.02em;
}

${typeUtilities}
`;

// ---- mark → geometry, SVG assets ---------------------------------------------------------------------------------

const BODY_D = [mark.body, ...mark.bars].join("");
const LID_D = mark.lid.join("");
const LABEL = "Hako";
const glyph = (body, lid) =>
  `<path fill="${body}" fill-rule="evenodd" d="${BODY_D}"/><path fill="${lid}" d="${LID_D}"/>`;
const svg = (inner, title = LABEL) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${mark.viewBox}" role="img" aria-label="${title}"><title>${title}</title>${inner}</svg>\n`;
const iconOffset = (mark.size * (1 - mark.appIcon.scale)) / 2;
const appIcon = svg(
  `<rect width="${mark.size}" height="${mark.size}" rx="${mark.appIcon.radius}" fill="${INK}"/>` +
    `<g transform="translate(${iconOffset} ${iconOffset}) scale(${mark.appIcon.scale})">${glyph(PAPER, tokens.accent.value)}</g>`,
);
// The browser tab: the bare glyph, ink on light tab bars and paper on dark ones.
const favicon = svg(
  `<style>.b{fill:${INK}}@media (prefers-color-scheme:dark){.b{fill:${themes.dark.foreground}}}</style>` +
    `<path class="b" fill-rule="evenodd" d="${BODY_D}"/><path fill="${tokens.accent.value}" d="${LID_D}"/>`,
);
const assets = {
  "hako-mark.svg": svg(glyph(INK, tokens.accent.value)),
  // For pages that inline it (@hako/identity's `hako` mark): the body in the current text colour, the lid in the
  // accent, as HakoMark draws it, so it reads on the light and the dark card alike.
  "hako-mark-adaptive.svg": svg(glyph("currentColor", tokens.accent.value)),
  "hako-mark-ink.svg": svg(glyph(INK, INK)),
  "hako-mark-inverse.svg": svg(glyph(PAPER, PAPER)),
  "app-icon.svg": appIcon,
  "favicon.svg": favicon,
};

const ts = `${TS_HEADER}// For code that cannot use class names (charts, canvas, OG images, the MCP view's host fallbacks) and the Senryo
// scales (type, space, radius, elevation, motion, spring, layout, size) components build their styles from.
export const tokens = ${JSON.stringify(
  {
    name: tokens.name,
    defaultMode: tokens.defaultMode,
    radius,
    accent: { name: tokens.accent.name, kanji: tokens.accent.kanji, value: tokens.accent.value },
    fonts: { display: tokens.fonts.display, body: tokens.fonts.body, mono: tokens.fonts.mono },
    scale: tokens.scale,
    themes,
  },
  null,
  2,
)} as const;

export type ThemeName = keyof typeof tokens.themes;
export type TokenName = keyof typeof tokens.themes.light;
`;

const markTs = `${TS_HEADER}/** The Hako mark's geometry (mark.json): the body with 目's two bars cut out (even-odd), and the open lid. */
export const MARK = ${JSON.stringify({ viewBox: mark.viewBox, body: BODY_D, lid: LID_D }, null, 2)} as const;

/** The SVG assets as text, for routes that serve them (app icons, OG images) without reading files. */
export const MARK_SVG = ${JSON.stringify(assets, null, 2)} as const;
`;

mkdirSync(here("generated"), { recursive: true });
mkdirSync(here("assets"), { recursive: true });
writeFileSync(here("generated/web.css"), web);
writeFileSync(here("generated/tokens.ts"), ts);
writeFileSync(here("generated/mark.ts"), markTs);
for (const [file, body] of Object.entries(assets)) writeFileSync(here(`assets/${file}`), body);
console.log(
  `brand: ${names.length} tokens x ${Object.keys(themes).length} themes, ${Object.keys(tokens.scale.type).length} type roles -> generated/{web.css,tokens.ts,mark.ts}; ${Object.keys(assets).length} mark assets`,
);
